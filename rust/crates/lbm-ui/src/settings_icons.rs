    pub(crate) fn paint(self, ui: &Ui, rect: Rect, color: Color32) {
        if !ui.is_rect_visible(rect) {
            return;
        }
        let pixels = (rect.width() * ui.ctx().pixels_per_point()).ceil().max(1.) as u32;
        let key = egui::Id::new(("settings-icon", self));
        let cached = ui
            .ctx()
            .data(|d| d.get_temp::<(u32, Color32, egui::TextureHandle)>(key));
        let texture = match cached {
            Some((size, tint, texture)) if size == pixels && tint == color => texture,
            _ => {
                let svg = format!(
                    r#"<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"><path fill="black" d="{}"/></svg>"#,
                    self.path()
                );
                let tree = lbm_icons::load(
                    svg.as_bytes(),
                    lbm_icons::Rgba(color.r(), color.g(), color.b(), 255),
                )
                .expect("bundled settings icon");
                let rgba = lbm_icons::render(&tree, pixels).expect("settings icon dimensions");
                let texture = ui.ctx().load_texture(
                    format!("settings-{self:?}"),
                    egui::ColorImage::from_rgba_premultiplied([pixels as usize; 2], &rgba),
                    egui::TextureOptions::LINEAR,
                );
                ui.ctx()
                    .data_mut(|d| d.insert_temp(key, (pixels, color, texture.clone())));
                texture
            }
        };
        ui.painter().image(
            texture.id(),
            rect,
            Rect::from_min_max(egui::Pos2::ZERO, egui::pos2(1., 1.)),
            Color32::from_white_alpha(color.a()),
        );
    }

    pub(crate) fn show(self, ui: &mut Ui) {
        let (rect, _) = ui.allocate_exact_size(vec2(18., 18.), egui::Sense::hover());
        let color = if ui.is_enabled() {
            crate::theme::MUTED
        } else {
            crate::theme::MUTED.gamma_multiply(0.4)
        };
        self.paint(ui, rect, color);
    }
